@lru_cache(maxsize=16)
def _replacement_rule(replacements: tuple[tuple[str, str], ...]):
    ordered = tuple(sorted(replacements, key=lambda row: len(row[0]), reverse=True))
    mapping = {source.casefold(): target for source, target in ordered}
    pattern = re.compile(r"(?<![A-Za-z])(?:" + "|".join(re.escape(source) for source, _ in ordered) + r")(?![A-Za-z])", flags=re.I)
    return pattern, mapping


def _replace(text: str, replacements: tuple[tuple[str, str], ...]) -> str:
    value = str(text or "")
    protected: dict[str, str] = {}
    for index, token in enumerate(("LEYA MOULD", "HMould", "WhatsApp", "PET", "OEM", "ODM", "DFM")):
        marker = f"\uE000{index}\uE001"
        # Protect standalone product/brand tokens only.  A substring match
        # would turn ``repeatable`` into ``rePETable`` when PET is protected.
        value = re.sub(r"(?<![A-Za-z])" + re.escape(token) + r"(?![A-Za-z])", marker, value, flags=re.I)
        protected[marker] = token
    # One compiled alternation is materially faster than running hundreds of
    # individual regular expressions for every product, model and article
    # field. Word boundaries are retained so short technical tokens do not
    # alter larger words.
    pattern, mapping = _replacement_rule(tuple(replacements))
    value = pattern.sub(lambda match: mapping.get(match.group(0).casefold(), match.group(0)), value)
    for marker, token in protected.items():
        value = value.replace(marker, token)
    return re.sub(r"\s{2,}", " ", value).strip()


def spanish_model_text(value: Any) -> str:
    """Translate only the descriptive shell of a model name/ALT."""
    text = re.sub(r"[-_]+", " ", str(value or "")).strip()
    text = _replace(text, _MODEL_REPLACEMENTS)
    return re.sub(r"\s+", " ", text).strip()


def spanish_model_description(value: Any) -> str:
    text = str(value or "").strip()
    if not text:
        return "Referencia de catálogo HMould. La configuración final de cavidades, el acero, la interfaz de máquina y la evidencia de producción se confirman durante la revisión del proyecto de LEYA MOULD."
    # Apply phrase-level repairs before short glossary tokens.  Otherwise a
    # legacy D1 phrase such as ``Cap Auxiliary Machines`` is split by the
    # generic ``cap`` replacement and can no longer be repaired as a whole.
    value = _replace(text, _MIXED_CLEANUP_REPLACEMENTS)
    value = _replace(value, (("HMould catalogue model reference", "Referencia de catálogo de HMould"), ("Final cavity plan", "La configuración final de cavidades"), ("steel", "el acero"), ("machine interface", "la interfaz de máquina"), ("production evidence", "la evidencia de producción"), ("are confirmed during LEYA MOULD project review", "se confirman durante la revisión del proyecto de LEYA MOULD")) + _EDITORIAL_REPLACEMENTS + _GENERAL_REPLACEMENTS)
    return _replace(value, _MIXED_CLEANUP_REPLACEMENTS)


def spanish_editorial_copy(value: Any) -> Any:
    """Return a copy with only Spanish-facing strings cleaned up."""
    def clean(node: Any, active: bool = False) -> Any:
        if isinstance(node, str):
            # Editorial rows may include category labels and legacy UI phrases
            # in addition to sentence prose.  Use the complete reviewed
            # Spanish glossary for the active branch so a mixed D1 row cannot
            # leak labels such as “brief”, “teams” or “Cycle Target”.
            return spanish_ui_text(node) if active else node
        if isinstance(node, list):
            return [clean(item, active) for item in node]
        if isinstance(node, dict):
            result = {}
            for key, item in node.items():
                # Editorial objects use {en: ..., es: ...} at every level.
                # Keep English and owner metadata byte-for-byte unchanged; only
                # clean the Spanish branch and the language-neutral evidence
                # source labels.
                result[key] = clean(item, active or key == "es" or key == "evidenceSources")
            return result
        return copy.deepcopy(node)
    return clean(value)


def spanish_ui_text(value: Any) -> str:
    """Translate reviewed UI/category phrases without altering model facts."""
    text = str(value or "")
    # A few legacy reference specs store media paths inside tuples rather than
    # under a named ``image`` key.  Treat a complete asset URL as opaque so
    # glossary terms such as ``gallon`` or ``water`` cannot corrupt the file
    # name during the Spanish boundary pass.
    if re.fullmatch(r"(?:https?://|/|[A-Za-z]:[\\/])\S+\.(?:svg|png|jpe?g|webp|gif|pdf)(?:\?\S*)?", text.strip(), flags=re.I):
        return text
    # Phrase-level cleanup must run once before the short generic glossary and
    # once after it.  D1 rows frequently contain mixed fragments such as
    # ``Cap Auxiliary Machines`` or ``Your Trusted ...``; translating ``Cap``
    # first would destroy the phrase boundary and leave an English fragment
    # that a later pass can no longer recognise.
    value = _replace(text, _MIXED_CLEANUP_REPLACEMENTS)
    value = _replace(value, _UI_REPLACEMENTS + _EDITORIAL_REPLACEMENTS + _GENERAL_REPLACEMENTS)
    return _replace(value, _MIXED_CLEANUP_REPLACEMENTS)


def spanish_ui_copy(value: Any) -> Any:
    """Copy a page-specific English fallback into its Spanish UI form."""
    if isinstance(value, str):
        return spanish_ui_text(value)
    if isinstance(value, tuple):
        return tuple(spanish_ui_copy(item) for item in value)
    if isinstance(value, list):
        return [spanish_ui_copy(item) for item in value]
    if isinstance(value, dict):
        # Never translate route, media, identifier or source fields.  Several
        # legacy rows use filenames such as ``water-cap.jpg``; translating a
        # path at the locale boundary would make the reviewed asset disappear.
        opaque_keys = {
            "image", "hero_image", "src", "href", "route", "slug", "model", "videoId",
            "publishedAt", "date", "source", "sourceUrl", "sourceImage",
            "pdfUrl", "pdfSha256", "imagePath", "cover", "canonical",
            "ogImage", "og_image", "url", "link", "id", "key", "code",
        }
        return {key: (copy.deepcopy(item) if str(key) in opaque_keys else spanish_ui_copy(item)) for key, item in value.items()}
    return copy.deepcopy(value)


def repair_es_common_copy(current: Any) -> dict:
    """Fill missing/stale Spanish fields while leaving owner-specific text intact."""
    result = copy.deepcopy(current) if isinstance(current, dict) else {}
    result.setdefault("es", {})
    if not isinstance(result["es"], dict):
        result["es"] = {}
    return result
