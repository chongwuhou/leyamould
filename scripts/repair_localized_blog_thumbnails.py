#!/usr/bin/env python3
"""Fix only translated blog LIST thumbnails explicitly linked to the right post.

Translated article cover, OG metadata and BlogPosting JSON-LD are already
generated by render_locales. No arbitrary global PPT-media replacement.
"""
import json
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent
OVERRIDES=json.loads((ROOT/"data/blog-cover-overrides.json").read_text(encoding="utf8"))
ORIGINALS={p["slug"]:"/media/ppt/"+p["cover"] for p in
           json.loads((ROOT/"data/blog-guides.json").read_text(encoding="utf8"))}
LOCALES=("es","pt","ru","tr")

def apply(dist):
    dist=Path(dist)
    updated=0
    for lang in LOCALES:
        page=dist/lang/"blog/index.html"
        body=page.read_text(encoding="utf8")
        for slug,new in OVERRIDES.items():
            old=ORIGINALS[slug]
            pattern=(r'(<a class="news-card__image" href="/'+lang+
                r'/blog/'+re.escape(slug)+
                r'/"><img src=")'+re.escape(old)+r'(")')
            body,n=re.subn(pattern,lambda m:m.group(1)+new+m.group(2),body)
            if n!=1:
                raise ValueError("Expected one translated blog listing card "+
                                 lang+"/"+slug+"; got "+str(n))
            updated+=n
        page.write_text(body,encoding="utf8")
    print("XUYI_LOCALIZED_BLOG_THUMBNAIL_DEDUP",updated)
    return updated

if __name__=="__main__":
    apply(ROOT/"dist")