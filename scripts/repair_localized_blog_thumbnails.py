#!/usr/bin/env python3
"""Correct specific translated Blog cards, article covers and related cards.

OG and JSON-LD are already generated by render_locales. Never replace PPT
image paths globally because other articles legitimately share those sources.
"""
import json
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent
OVERRIDES=json.loads((ROOT/"data/blog-cover-overrides.json").read_text(encoding="utf8"))
ORIGINALS={p["slug"]:"/media/ppt/"+p["cover"] for p in
           json.loads((ROOT/"data/blog-guides.json").read_text(encoding="utf8"))}
LOCALES=("es","pt","ru","tr")

def apply(dist):
    dist=Path(dist)
    updated=0
    details=0
    related=0
    for lang in LOCALES:
        page=dist/lang/"blog/index.html"
        body=page.read_text(encoding="utf8")
        for slug,new in OVERRIDES.items():
            old=ORIGINALS[slug]
            pattern=(r'(<a class="news-card__image" href="/'+lang+
                r'/blog/'+re.escape(slug)+
                r'/"><img src=")'+re.escape(old)+r'(")')
            body,n=re.subn(pattern,lambda m:m.group(1)+new+m.group(2),body)
            if n!=1:
                raise ValueError("Expected one translated blog listing card "+
                                 lang+"/"+slug+"; got "+str(n))
            updated+=n
        page.write_text(body,encoding="utf8")

        # The translated article body still contained the old PPT cover,
        # even though metadata and listing cards had already been refreshed.
        for slug in ORIGINALS:
            detail_page=dist/lang/"blog"/slug/"index.html"
            document=detail_page.read_text(encoding="utf8")
            if slug in OVERRIDES:
                old=ORIGINALS[slug]
                new=OVERRIDES[slug]
                cover=(r'(<div class="blog-detail__cover"><img src=")'
                       +re.escape(old)+r'(")')
                document,n=re.subn(cover,lambda m:m.group(1)+new+m.group(2),document)
                if n!=1:
                    raise ValueError("Translated article cover mismatch "+lang+"/"+slug+": "+str(n))
                details+=n

            for linked,new in OVERRIDES.items():
                original=ORIGINALS[linked]
                pattern=(r'(<article class="blog-related__item"><a href="/'
                         +lang+r'/blog/'+re.escape(linked)+
                         r'/"><img src=")'+re.escape(original)+r'(")')
                document,n=re.subn(pattern,lambda m:m.group(1)+new+m.group(2),document)
                related+=n
            detail_page.write_text(document,encoding="utf8")
    print("XUYI_LOCALIZED_BLOG_IMAGE_SYNC",
          "listing",updated,"detail",details,"related",related)
    return updated

if __name__=="__main__":
    apply(ROOT/"dist")