#!/usr/bin/env python3
"""Model-specific Materials/Design/FAQ baseline, D1 precedence and FAQPage parity."""
from pathlib import Path
from hashlib import sha256
import collections,json,re,sys
ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT))
from site_renderer import SERIES
from product_content import details
from sku_factual_sections import THIRD20 as PEERS,BASE,LANGS,apply,section,material_annotation,facts
from seo_structured_components import visible_faq

assert len(PEERS)==20 and len(BASE)>=len(PEERS)
cohorts=collections.Counter(SERIES[s]["category"] for s in PEERS)
assert sorted(cohorts.values())==[6,6,8] and len(cohorts)==3,cohorts
snapshot=json.loads((ROOT/"_local_ops/build-snapshot.json").read_text(encoding="utf8"))
D1={(x["resourceId"][5:],x["locale"]):x["content"]["mainHtml"]
    for x in snapshot["translations"] if x.get("resourceId","").startswith("page:")}
seen=0
for sku,peer in PEERS.items():
    row=SERIES[sku]
    assert row["category"]==SERIES[peer]["category"] and sku!=peer
    assert not row.get("galleryReference") and not row.get("loNew")
    for locale in LANGS:
        raw=details(row) if locale=="en" else D1.get(("/products/"+sku+"/",locale))
        assert isinstance(raw,str),(sku,locale,"missing D1 translation")
        output=apply(raw,row,locale)
        once_more=apply(output,row,locale)
        assert once_more==output,(sku,locale,"second injection")
        assert "data-sku-material=" not in output  # generated by separate approved Materials renderer
        # Independent section hashes: owner updates to one module do not
        # block the other module, and are never reverted.
        for kind in ("design","faq"):
            original=section(raw,kind)
            assert original is not None,(sku,locale,kind)
            digest=sha256(original[2].encode("utf8")).hexdigest()[:16]
            updated=section(output,kind)
            assert updated is not None
            if digest==BASE[sku][locale][kind]:
                assert updated[2]!=original[2],(sku,locale,kind,"missing reviewed module")
                assert sku in updated[2] and peer in updated[2],(sku,locale,kind)
            else:
                assert updated[2]==original[2],(sku,locale,kind,"edited owner module overwritten")
            changed=raw[:original[0]]+original[2].replace('<div class="section__head">','<div class="section__head" data-editor-custom="yes">',1)+raw[original[1]:]
            assert changed!=raw
            owner_output=apply(changed,row,locale)
            preserved=section(owner_output,kind)
            assert preserved is not None and preserved[2]==section(changed,kind)[2],(sku,locale,"owner edit lost")
        evidence=material_annotation(row,locale)
        f=facts(row,locale,SERIES)
        assert sku in evidence and peer in evidence and f["mat"] in evidence
        assert not re.search(r'(?i)(certified leakproof|guaranteed bpa[- ]?free)',evidence)
        assert ("PC" not in f["mat"] or "PC" in evidence)
        document=(ROOT/"dist"/("" if locale=="en" else locale)/"products"/sku/"index.html").read_text(encoding="utf8")
        assert document.count('data-sku-material="'+sku+'"')==1,(sku,locale,"material body block")
        assert evidence in document,(sku,locale,"material evidence not from source renderer")
        for kind in ("design","faq"):
            actual=section(document,kind)
            assert actual and actual[2]==section(output,kind)[2],(sku,locale,kind,"render differs from source")
        pairs=visible_faq(document)
        assert len(pairs)==4 and all(sku in q for q,a in pairs),(sku,locale,"not four model-specific FAQs")
        scripts=re.findall(r'<script type="application/ld\+json">(.*?)</script>',document,re.S)
        schemas=[obj for rawj in scripts if isinstance((obj:=json.loads(rawj)),dict) and obj.get("@type")=="FAQPage"]
        assert len(schemas)==1,(sku,locale,"FAQPage missing or doubled")
        visible_schema=[(x["name"],x["acceptedAnswer"]["text"]) for x in schemas[0]["mainEntity"]]
        assert visible_schema==pairs,(sku,locale,"FAQ JSON-LD out of sync with visible questions")
        seen+=1
# An editor can replace a FAQ module wholesale and its visible Q&A must
# generate the schema, rather than restoring our older SKU fallback questions.
from sku_factual_sections import section as chosen_section
from product_material_performance import inject as inject_materials
from seo_structured_components import add_at_render
owner_product=SERIES["2401"]
owner_source=details(owner_product)
old_faq=chosen_section(owner_source,"faq")
assert old_faq
editor_section='<section class="section section--soft"><div class="shell"><div class="section__head"><h2>Frequently Asked Questions</h2></div><div class="faq-list"><details><summary>Owner selected lid for 2401?</summary><p>Discuss the custom cap drawing and sample with the factory; no production lid choice is assumed.</p></details></div></div></section>'
owner_body=owner_source[:old_faq[0]]+editor_section+owner_source[old_faq[1]:]
assert chosen_section(apply(owner_body,owner_product,"en"),"faq")[2]==editor_section
envelope='<html><head></head><body><main id="main-content">'+apply(owner_body,owner_product,"en")+'</main></body></html>'
with_schema=add_at_render(envelope,"/products/2401/","en")
assert len(visible_faq(with_schema))==1
assert visible_faq(with_schema)[0][0]=="Owner selected lid for 2401?"
graphs=[json.loads(raw) for raw in re.findall(r'<script type="application/ld\+json">(.*?)</script>',with_schema,re.S)]
assert len([x for x in graphs if x.get("@type")=="FAQPage"])==1
editor_material=owner_source.replace('</section><section class="section section--soft product-content">',
 '</section><section class="section material-brief" id="material-performance"><div>Owner-selected exact 2095 materials</div></section><section class="section section--soft product-content">',1)
assert editor_material!=owner_source and inject_materials(editor_material,owner_product,"en","/products/2401/")==editor_material
unselected=SERIES["2506"] # still held: anomalous 60ml source, no factual H2 curation
plain=details(unselected)
assert apply(plain,unselected,"en")==plain
assert material_annotation(unselected,"en")==""
future={**unselected,"model":"NEW","slug":"approved-2027-new"}
assert apply(plain,future,"en")==plain
print("XUYI_THIRD20_THREE_COLLECTIONS_FACTUAL_MATERIAL_DESIGN_FAQ_CMS_SCHEMA_PASSED",seen,"pages")